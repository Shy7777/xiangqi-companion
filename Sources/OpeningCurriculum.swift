    private static func line(_ id: String, _ title: String, _ intent: String, _ adaptation: String,
                             side: Side = .red, _ script: String) -> StudyLine {
        let moves = script.split(separator: "\n").map { row -> StudyMove in
            let fields = row.split(separator: "|", omittingEmptySubsequences: false).map(String.init)
            precondition(fields.count == 3, "Opening study row must contain move, explanation and hint")
            return StudyMove(fields[0].trimmingCharacters(in: .whitespaces), fields[1], hint: fields[2])
        }
        return StudyLine(id: "opening-" + id, title: title, intent: intent, adaptation: adaptation,
                         studentSide: side, moves: moves)
    }

