        return lesson
    }

    private static func lineID(_ topic: String, _ index: Int) -> String { topic + "-excerpt-\(index + 1)" }

    private static func fact(position: Position, item: StudyMove) -> String {
        let move = Move(uci: item.uci)!
        let capture = position[move.to].map { "，吃去\($0.side.label)\($0.symbol)" } ?? "，此着没有吃子"
        return "原谱\(position.sideToMove.label)走\(position.notation(for: move))（\(move.from)→\(move.to)）\(capture)。"
    }

    private static func makeLine(topic: Topic, index: Int, segment: Segment) -> StudyLine {
        let parent = originals[segment.game], states = originalPositions[segment.game]
        let notes = Dictionary(uniqueKeysWithValues: segment.points.map { ($0.ply, $0) })
        let moves = (0..<10).map { offset -> StudyMove in
            let p = states[segment.start + offset], item = parent.moves[segment.start + offset]
            let comment = notes[offset]?.comment ?? "这是该局的实际续着。观察它改变了哪条行动路线；不要假设对手在其他选择后仍会照此应答。"
            return StudyMove(item.uci, fact(position: p, item: item) + comment,
                             hint: notes[offset]?.focus ?? "先检查\(p.sideToMove.label)是否被将，再核对吃子、回吃与走后留下的目标。")
        }
        let game = parent.game!
        var line = StudyLine(id: lineID(topic.id, index),
            title: "\(index + 1) · \(segment.title)", intent: segment.question,
            adaptation: "来源：\(game.red)—\(game.black)，\(game.date)。原全局第 \(segment.start + 1)–\(segment.start + 10) 半步的专题截段，非新增完整对局。\(topic.adapt) 选择别的合理着法后，只能显式回到原谱继续研究，不能把不同棋面的续着拼接。",
            startingFEN: states[segment.start].fen, studentSide: states[segment.start].sideToMove, moves: moves)
        line.checkpoints = segment.points.map { note in
            StudyCheckpoint(ply: note.ply, title: note.title, prompt: note.question,
                            focus: note.focus, explanation: moves[note.ply].explanation)
        }
        line.variations = researchVariations[line.id]
        return line
    }

